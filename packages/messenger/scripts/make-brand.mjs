// Regenerates brands/mosadd/* and skins/august from the mosADD design system in RADS
// (systemy/mosadd/project/tokens.json, block `sierpienFF97e89aa`). The source is read, never written:
// a change to the design system is a commit in RADS first, then this script, then a commit here.
//
//   node scripts/make-brand.mjs [path/to/tokens.json]
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = process.argv[2] ?? "C:/RA-design-systems/systemy/mosadd/project/tokens.json";
const raw = readFileSync(src, "utf8");
const ds = JSON.parse(raw).sierpienFF97e89aa;
const sha = createHash("sha256").update(raw).digest("hex").slice(0, 12);

const hsl = (v) => {
  const m = /^hsl\(\s*(\d+(?:\.\d+)?)\s+(\d+(?:\.\d+)?)%\s+(\d+(?:\.\d+)?)%\s*\)$/.exec(v);
  if (!m) throw new Error(`not a plain hsl(): ${v}`);
  return [Number(m[1]), Number(m[2]), Number(m[3])];
};
const fmt = ([h, s, l]) => `hsl(${h} ${s}% ${l}%)`;
const hex = (v) => {
  const [h, s0, l0] = hsl(v);
  const s = s0 / 100, l = l0 / 100, k = (n) => (n + h / 30) % 12, a = s * Math.min(l, 1 - l);
  const f = (n) => Math.round(255 * (l - a * Math.max(-1, Math.min(k(n) - 3, Math.min(9 - k(n), 1))))).toString(16).padStart(2, "0");
  return `#${f(0)}${f(8)}${f(4)}`;
};
const mode = (name) => Object.fromEntries(Object.entries(ds.color[name]).filter(([, v]) => v && v.value).map(([k, v]) => [k, v.value]));
const dark = mode("dark"), light = mode("light");

// Derived tokens (the design system has no "soft", "faint" or "line-strong"): fixed rules, written down in
// TOKENY-MOSADD-DLA-POXI.md. soft = midway between foreground and muted-foreground; faint = muted-foreground
// 15 points toward the background; line-strong = border 8 points away from the background.
const derive = (t, towardsDark) => {
  const [fh, fs, fl] = hsl(t.foreground), [mh, ms, ml] = hsl(t["muted-foreground"]), [bh, bs, bl] = hsl(t.border);
  return {
    soft: fmt([+((fh + mh) / 2).toFixed(0), +((fs + ms) / 2).toFixed(0), +((fl + ml) / 2).toFixed(0)]),
    faint: fmt([mh, ms, Math.max(0, Math.min(100, ml + (towardsDark ? -15 : 15)))]),
    "line-strong": fmt([bh, bs, Math.max(0, Math.min(100, bl + (towardsDark ? 8 : -8)))]),
  };
};

const brand = (t, towardsDark, modeName) => {
  const d = derive(t, towardsDark);
  return {
    id: "mosadd",
    name: "mosADD",
    logo: { src: "/brands/mosadd/logo.svg", alt: "mosADD" },
    mode: modeName,
    tokens: {
      bg: t.background, ink: t.foreground, text: t.foreground, muted: t["muted-foreground"], soft: d.soft, faint: d.faint,
      line: t.border, "line-strong": d["line-strong"], chip: t.secondary, "chip-hover": t.accent, card: t.card,
      accent: t.primary, ok: t.primary, danger: t.destructive, warn: t.warning,
      "shadow-card": towardsDark ? "0 0 8px hsl(146 72% 45% / 0.15)" : "none", "shadow-soft": "none", radius: ds.radius.var.value,
      font: ds.typography.brand.value, mono: ds.typography.mono.value,
      aurora: [],
    },
    copy: {
      heroTitle: "Build your own messenger",
      heroLede: "Dress the mosADD messenger in your own skin: colours, type, corners, backdrop, name and logo. Same blocks, same encryption, your look.",
      omnibarPlaceholder: "Dark navy, port at night, amber accent, fewer rounded corners…",
      chips: ["Port at night", "Event security", "Club", "Fleet desk"],
    },
  };
};

const out = join(root, "brands", "mosadd");
mkdirSync(out, { recursive: true });
const b = brand(dark, true, "dark"), bl = brand(light, false, "light");
// the light file is the same brand in the other mode: tokens differ, copy and logo are the same
writeFileSync(join(out, "brand.json"), JSON.stringify(b, null, 2) + "\n");
writeFileSync(join(out, "brand.light.json"), JSON.stringify(bl, null, 2) + "\n");

const css = (t, sel) => `${sel}{\n${Object.entries(t.tokens).filter(([k]) => k !== "aurora").map(([k, v]) => `  --${k}:${v};`).join("\n")}\n}\n`;
writeFileSync(
  join(out, "tokens.css"),
  `/* mosADD design system, "August classes" (sierpienFF97e89aa), as the variable names the POXI studio already knows.\n   Generated by scripts/make-brand.mjs from RADS tokens.json (sha256 ${sha}). No borders around elements (D41.58): \`line\` is for dividers only. */\n` +
    css(b, ":root") + css(bl, '[data-mode="light"]'),
);
writeFileSync(join(out, "SOURCE.md"), `# Source of brand.json\n\nGenerated by \`scripts/make-brand.mjs\` from \`systemy/mosadd/project/tokens.json\` (RADS), block \`sierpienFF97e89aa\`,\nfile sha256 prefix \`${sha}\`. Do not edit by hand: change the design system in RADS, then regenerate.\n\nDerived tokens (not in the design system): \`soft\`, \`faint\`, \`line-strong\`. Rules are in the script.\nThe logo is the canon kolovrat (\`assets/Znak/favicon.svg\` in RADS); the dotted wordmark waits for the King's acceptance (D41.52).\n`);

// The "August" skin for messenger.json: the same tokens as hex, for the shared validator.
const tok = (t, ptt) => ({
  background: hex(t.background), surface: hex(t.card), border: hex(t.border), text: hex(t.foreground), textMuted: hex(t["muted-foreground"]),
  accent: hex(t.primary), onAccent: hex(t["primary-foreground"]), warning: hex(t.warning), error: hex(t.destructive),
  pttTransmit: hex(ptt.tx), pttListen: hex(ptt.listen),
});
const ch = (t) => ({ mDM: hex(t["mod-dm"]), mIRC: hex(t["mod-irc"]), mAYL: hex(t["mod-ayl"]), mURL: hex(t["mod-url"]) });
// PTT states are not in the design system: transmit = destructive, listen = the mDM green.
const skin = {
  format: "mosadd.skin",
  formatVersion: 1,
  name: "August",
  logo: undefined,
  defaultMode: "dark",
  // Dark only, on purpose: the real light theme fails WCAG AA (white on hsl(145 100% 28%) is 4.21:1, needs 4.5:1).
  // That is a finding about the design system, reported to its owner; this script does not "fix" it by changing colours.
  modes: ["dark"],
  tokens: { dark: tok(dark, { tx: dark.destructive, listen: dark["mod-dm"] }) },
  channels: { dark: ch(dark) },
  fonts: { text: "Space Grotesk", headings: "Space Grotesk" },
  radius: "square",
  density: "comfortable",
  backdrop: { kind: "lidar" },
};
mkdirSync(join(root, "skins", "august"), { recursive: true });
writeFileSync(join(root, "skins", "august", "skin.json"), JSON.stringify(JSON.parse(JSON.stringify(skin)), null, 2) + "\n");
console.log("ok", sha);
