#!/usr/bin/env node
// Builds install/install.sh and install/install.ps1 from packages/m0s/m0s.mjs.
// Each installer carries the whole m0s.mjs inline (a quoted heredoc / a literal here-string), so a
// one-line install pinned to a commit runs exactly the code of that commit — nothing else is fetched.
//
//   node scripts/build-installers.mjs          write both installers
//   node scripts/build-installers.mjs --check  exit 1 if they are out of date (the m0s test suite runs this)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(root, 'packages', 'm0s', 'm0s.mjs');
const REPO = 'https://github.com/Hei33enberg/mosADD-OS';
const RAW = 'https://raw.githubusercontent.com/Hei33enberg/mosADD-OS/<commit>/install';

export function buildInstallers(source = readFileSync(SRC, 'utf8')) {
  const js = source.replace(/\r\n/g, '\n').replace(/\n*$/, '\n');
  if (/[^\x00-\x7f]/.test(js)) throw new Error('m0s.mjs must stay ASCII-only (it is embedded in sh and PowerShell)');
  if (/^M0S_SOURCE_EOF$/m.test(js)) throw new Error('m0s.mjs contains the heredoc terminator');
  if (/^'@/m.test(js)) throw new Error("m0s.mjs contains a line starting with '@ (PowerShell here-string terminator)");
  const version = js.match(/export const VERSION = '([^']+)'/)[1];

  const sh = `#!/bin/sh
# m.0S installer ${version} (MIT). Writes the m.0S MCP entry into the AI hosts found on this machine.
#   curl -fsSL ${RAW}/install.sh | sh
#   curl -fsSL ${RAW}/install.sh | sh -s -- --host cursor,codex   # only these hosts
#   curl -fsSL ${RAW}/install.sh | sh -s -- --dry-run             # show, touch no host config (still caches m0s.mjs and the signed list in ~/.m0s)
# Needs Node.js >= 18. Your key goes in MOSADD_KEY (https://app.mosadd.dev); hosts get a reference to it.
# GENERATED by scripts/build-installers.mjs from packages/m0s/m0s.mjs - do not edit by hand.
set -eu
if ! command -v node >/dev/null 2>&1 || ! node -e 'process.exit(Number(process.versions.node.split(".")[0]) >= 18 ? 0 : 1)'; then
  echo "m0s: Node.js >= 18 is required (https://nodejs.org). Manual setup per host: ${REPO}/blob/main/docs/hosts.md" >&2
  exit 1
fi
M0S_DIR="\${M0S_HOME:-$HOME/.m0s}"
mkdir -p "$M0S_DIR"
cat > "$M0S_DIR/m0s.mjs" <<'M0S_SOURCE_EOF'
${js}M0S_SOURCE_EOF
exec node "$M0S_DIR/m0s.mjs" install "$@"
`;

  const ps1 = `# m.0S installer ${version} (MIT). Writes the m.0S MCP entry into the AI hosts found on this machine.
#   irm ${RAW}/install.ps1 | iex
#   & ([scriptblock]::Create((irm ${RAW}/install.ps1))) --host cursor,codex
#   & ([scriptblock]::Create((irm ${RAW}/install.ps1))) --dry-run
# Needs Node.js >= 18. Your key goes in $env:MOSADD_KEY (https://app.mosadd.dev); hosts get a reference to it.
# GENERATED by scripts/build-installers.mjs from packages/m0s/m0s.mjs - do not edit by hand.
# PowerShell reads an unquoted cursor,codex as an array; join it back so node sees --host cursor,codex.
$m0sArgs = @(foreach ($a in $args) { if ($a -is [System.Array]) { $a -join ',' } else { $a } })
$ErrorActionPreference = 'Stop'
$node = Get-Command node -ErrorAction SilentlyContinue
$nodeMajor = 0
if ($node) { try { $nodeMajor = [int](& $node.Source -e 'process.stdout.write(String(parseInt(process.versions.node)))') } catch { $nodeMajor = 0 } }
if ($nodeMajor -lt 18) {
  Write-Host "m0s: Node.js >= 18 is required (https://nodejs.org). Manual setup per host: ${REPO}/blob/main/docs/hosts.md"
  return
}
$m0sDir = if ($env:M0S_HOME) { $env:M0S_HOME } else { Join-Path $HOME '.m0s' }
New-Item -ItemType Directory -Force -Path $m0sDir | Out-Null
$m0sSource = @'
${js}'@
[System.IO.File]::WriteAllText((Join-Path $m0sDir 'm0s.mjs'), ($m0sSource -replace "\`r\`n", "\`n"), (New-Object System.Text.UTF8Encoding $false))
& $node.Source (Join-Path $m0sDir 'm0s.mjs') install @m0sArgs
`;
  return { sh, ps1, js };
}

/** The m0s.mjs text carried inside an installer (for the sync test). */
export function extractEmbedded(installer, kind) {
  const re = kind === 'sh' ? /<<'M0S_SOURCE_EOF'\n([\s\S]*?)M0S_SOURCE_EOF\n/ : /\$m0sSource = @'\r?\n([\s\S]*?)'@\r?\n/;
  const m = installer.replace(/\r\n/g, '\n').match(re);
  return m ? m[1] : null;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { sh, ps1 } = buildInstallers();
  const targets = [
    [join(root, 'install', 'install.sh'), sh],
    [join(root, 'install', 'install.ps1'), ps1],
  ];
  if (process.argv.includes('--check')) {
    const stale = targets.filter(([f, want]) => !existsSync(f) || readFileSync(f, 'utf8').replace(/\r\n/g, '\n') !== want);
    if (stale.length) {
      console.error(`stale installer(s): ${stale.map(([f]) => f).join(', ')} - run: node scripts/build-installers.mjs`);
      process.exit(1);
    }
    console.log('installers up to date');
  } else {
    for (const [f, want] of targets) writeFileSync(f, want);
    console.log('wrote install/install.sh and install/install.ps1');
  }
}
